// Only the finite App Lab transport. Real FS behavior is tested separately.
import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundle=await build({entryPoints:['dev/lab/navigation.ts'],bundle:true,format:'esm',write:false});
const {navigationFixture}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const devices=[{id:'local',name:'local',me:true},{id:'other',name:'other',me:false}];
const lab=navigationFixture(devices,'http://fixture.invalid',false);
const run=(command,args={})=>lab.request(command,{machine:'local',...args});
const ls=path=>run('ls',{path}).entries.map(entry=>entry.name);
const read=path=>run('read_text',{path});
const move=(from,to)=>run('rename_path',{from,to});
assert(lab.handles('rename_path'));
const notes=read('/preview/project/notes.md');
move('/preview/project/notes.md','/preview/project/docs/notes.md');
assert(!ls('/preview/project').includes('notes.md'));assert(ls('/preview/project/docs').includes('notes.md'));
assert.deepEqual(read('/preview/project/docs/notes.md'),notes);
assert.throws(()=>read('/preview/project/notes.md'));
assert.throws(()=>move('/preview/project/design.md','/preview/project/docs/notes.md'),/already exists/);
assert(ls('/preview/project').includes('design.md'));
const source=read('/preview/project/src/navigation.ts');
move('/preview/project/src','/preview/project/docs/src');
assert.deepEqual(read('/preview/project/docs/src/navigation.ts'),source);
assert.throws(()=>run('ls',{path:'/preview/project/src'}));
assert.throws(()=>move('/preview/project/docs','/preview/project/docs/src/docs'),/Invalid/);
assert.throws(()=>move('/preview/project/docs','/outside/docs'),/outside/);
move('/preview/project/README.md','/preview/project/readme.md');
assert(ls('/preview/project').includes('readme.md'));assert(!ls('/preview/project').includes('README.md'));
const next=run('write_text',{path:'/preview/project/docs/notes.md',text:'edited fixture',was:notes.digest});
assert.equal(read('/preview/project/docs/notes.md').text,'edited fixture');assert.equal(read('/preview/project/docs/notes.md').digest,next.digest);
assert(lab.request('ls',{machine:'other',path:'/home/lab/projects/project'}).entries.some(entry=>entry.name==='notes.md'),'machine snapshots are independent');
console.log('PASS finite App Lab rename fixture: file/directory moves, case spelling, conflicts, subtree bounds, old-path refusal, write cache and machine isolation (simulation only)');
