import assert from 'node:assert/strict';
import {build} from 'esbuild';
const built=await build({entryPoints:['src/lib/notification-banners.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const {collectNotifications,emptyNotifications,restoreNotifications,notificationMetadata,expireNotifications,sourceKey,scheduleNotifications,notificationPresence,QUEUE_LIMIT,BANNER_DURATION}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
const now=1700000000000;
const event=(id,at_ms=now,kind='turn_completed',extra={})=>({id,at_ms,kind,resolved:false,text:null,duration_ms:null,exit:null,...extra});
const row=(activity=[],extra={})=>({id:'gui/a',execution_home:'a'.repeat(64),title:'Private title',imported:false,observation_owner:null,activity,...extra});
const options={now,commandSeconds:30,present:true,onScreen:()=>false};
const collect=(state,rows,extra={})=>collectNotifications(state,rows,{...options,...extra});
const seeded=(r=row())=>collect(emptyNotifications(),[r]);
assert.equal(collect(emptyNotifications(),[row([event('old')])]).items.length,0,'Initial snapshots seed watermarks without a replay storm');
const baseline=seeded();
let result=collect(baseline,[row([event('new')])]);
assert.equal(result.items.length,1);assert.equal(result.items[0].expires,now+BANNER_DURATION);
assert.deepEqual(collect(result,[row([event('new')])]),result,'Polling does not reset the dismissal timer');
assert.equal(expireNotifications(result,now+BANNER_DURATION).items.length,0,'Banners expire');
assert.equal(collect({...result,items:[]},[row([event('new')])]).items.length,0,'Dismissed events do not reappear');
assert.equal(collect(baseline,[row([event('stale',now-120001)])]).items.length,0,'Old catch-up events do not become new banners');
assert.equal(collect(baseline,[row([event('visible')])],{onScreen:()=>true}).items.length,0);
const hidden=collect(baseline,[row([event('hidden')])],{present:false});
assert.equal(hidden.items.length,0);assert.equal(collect(hidden,[row([event('hidden')])]).items.length,0,'Background events are consumed without replay on resume');
const muted={...baseline,preferences:{[sourceKey(row())]:false}};
assert.equal(collect(muted,[row([event('mute')])]).items.length,0);
assert.equal(collect(seeded(row([],{imported:true})),[row([event('import')],{imported:true})]).items.length,0);
const followed={...seeded(row([],{imported:true})),preferences:{[sourceKey(row())]:true}};
assert.equal(collect(followed,[row([event('follow')],{imported:true})]).items.length,1);
result=collect(baseline,[row([event('ask',now,'needs_input')])]);
assert.equal(result.items.length,1);
assert.equal(collect(result,[row([event('ask',now,'needs_input',{resolved:true})])]).items.length,0,'Host resolution removes a request banner');
assert.equal(collect(result,[row([event('later',now+1)])]).items.some(i=>i.id==='ask'),false,'Later turn disposition supersedes old waiting request');
const other=row([],{execution_home:'b'.repeat(64)});
result=collect(collect(emptyNotifications(),[row(),other]),[row([event('same')]),{...other,activity:[event('same')]}]);
assert.equal(result.items.length,2);assert.notEqual(result.items[0].key,result.items[1].key,'Same session id on different machines stays distinct');
const command=event('cmd',now,'command_finished',{duration_ms:31000,exit:0});
assert.equal(collect(baseline,[row([command])]).items.length,1);
for(const extra of [{commandSeconds:0},{commandSeconds:60}])assert.equal(collect(baseline,[row([command])],extra).items.length,0);
assert.equal(collect(baseline,[row([{...command,exit:130}])]).items.length,0);
result=collect(baseline,[row(Array.from({length:20},(_,i)=>event(String(i),now+i)))]);
assert.equal(result.items.length,1,'Same-session burst coalesces in place');assert.equal(result.items[0].id,'19');
const metadata=JSON.stringify(notificationMetadata(result));
assert(!metadata.includes('Private title'));assert(!metadata.includes('items'));assert(!metadata.includes('text'));
assert.equal(restoreNotifications(metadata).items.length,0,'Reload restores only watermarks and preferences');
assert.equal(collect(restoreNotifications(metadata),[row(Array.from({length:20},(_,i)=>event(String(i),now+i)))]).items.length,0,'Reload cannot replay dismissed notices');
assert.equal(restoreNotifications(JSON.stringify({...result,items:[{title:'old private content'}]})).items.length,0,'Legacy inbox content is discarded');
assert.deepEqual(restoreNotifications('{bad'),emptyNotifications());
assert.equal(collect(baseline,[row([event('bad',NaN)])]).items.length,0);
console.log('Transient notifications: replay suppression, expiry, mute, routing, background consumption and metadata-only persistence passed');

const many=Array.from({length:6},(_,i)=>row([],{id:'gui/'+i,last:'Content '+i}));
const baselineMany=collect(emptyNotifications(),many);
let phone=collect({...baselineMany,capacity:1},many.slice(0,3).map(r=>({...r,activity:[event('new-'+r.id)]})));
assert.equal(phone.items.length,1);assert.equal(phone.queue.length,2);
assert(!('expires' in phone.queue[0]),'Queued notices do not start a timer');
phone=expireNotifications(phone,now+BANNER_DURATION);
assert.equal(phone.items[0].session,'gui/1');assert.equal(phone.items[0].expires,now+2*BANNER_DURATION,'Next notice gets its whole visible lifetime');
assert.equal(phone.items[0].preview,'Content 1');
phone=scheduleNotifications({...phone,items:phone.items.map(item=>({...item,paused:true}))},now+BANNER_DURATION+2000);
assert.equal(phone.items[0].remaining,6000);assert.equal(phone.items[0].expires,null);
const stable=phone.items[0];
phone=collect(phone,[{...many[1],last:'Updated content',activity:[event('updated',now+10000)]}],{now:now+10000});
assert.equal(phone.items[0].id,stable.id,'Touched content stays stable');assert.equal(phone.items[0].preview,'Content 1');
phone=scheduleNotifications({...phone,items:phone.items.map(item=>({...item,paused:false}))},now+12000);
assert.equal(phone.items[0].id,'updated');assert.equal(phone.items[0].key,stable.key);assert.equal(phone.items[0].expires,now+12000+BANNER_DURATION);
phone=scheduleNotifications({...phone,focused:false},now+13000);assert.equal(phone.items[0].expires,null);
phone=scheduleNotifications({...phone,focused:true},now+23000);assert.equal(phone.items[0].expires,now+23000+7000,'Window blur preserves remaining time');
let burst=collect(baselineMany,many.map(r=>({...r,activity:[event('burst-'+r.id)]})));
assert.equal(burst.items.length,1);assert.equal(burst.items[0].members.length,6,'Distinct-session bursts become one summary');
assert.deepEqual(collect(burst,many.map(r=>({...r,activity:[event('burst-'+r.id)]}))),burst,'Polling does not restart summary lifetime');
let protectedState=collect({...baselineMany,capacity:1},[{...many[0],activity:[event('first')]}]);
protectedState=scheduleNotifications({...protectedState,items:protectedState.items.map(item=>({...item,paused:true}))},now+1000);
protectedState=collect(protectedState,many.slice(1).map(r=>({...r,activity:[event('next-'+r.id,now+1001)]})),{now:now+1001});
assert.equal(protectedState.items[0].id,'first');assert.equal(protectedState.items.length,1,'Bursts cannot displace an interacted phone banner');
assert.equal(protectedState.queue.length,5);
protectedState=scheduleNotifications({...protectedState,items:protectedState.items.map(item=>({...item,paused:false}))},now+2000);
assert.equal(protectedState.items[0].members.length,6);
const hundred=Array.from({length:100},(_,i)=>row([],{id:'gui/bounded-'+i}));
burst=collect(collect(emptyNotifications(),hundred),hundred.map(r=>({...r,activity:[event('b-'+r.id)]})));
assert.equal(burst.items[0].members.length,QUEUE_LIMIT,'Retained burst content is bounded');
const stale=expireNotifications({...baselineMany,capacity:1,queue:[{...event('stale',now-120001),session:'old',home:'a',title:'old',preview:null}]},now);
assert.equal(stale.items.length,0);assert.equal(stale.queue.length,0,'Stale queued notices are discarded');
assert.equal(JSON.stringify(notificationMetadata(burst)).includes('Content'),false);
console.log('Notification scheduling: coalescing, visible-only clocks, touch/window pause, stable interaction, bounded queue, burst summaries and previews passed');

const cachedRows={},freshRows={},laterRows={};
let presence=notificationPresence({waiting:true,snapshot:null},cachedRows,false);
assert.equal(presence.deliver,false);
presence=notificationPresence(presence.next,cachedRows,true);
assert.equal(presence.deliver,false);assert.equal(presence.next.waiting,true,'Cached resume rows cannot release catch-up suppression');
presence=notificationPresence(presence.next,freshRows,true);
assert.equal(presence.deliver,false);assert.equal(presence.next.waiting,false,'First new host snapshot seeds quietly');
presence=notificationPresence(presence.next,laterRows,true);assert.equal(presence.deliver,true,'Only events after the fresh foreground snapshot notify');
presence=notificationPresence(presence.next,laterRows,false);assert.equal(presence.deliver,false);assert.equal(presence.next.waiting,true);
console.log('Notification presence: cached/fresh foreground boundary and background suppression passed');
