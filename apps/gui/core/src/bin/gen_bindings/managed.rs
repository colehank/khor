//! A complete staged export, with one recoverable directory publication.
//! Only the exact paths in our journal may be recovered or removed.
use serde::{Deserialize, Serialize};
use std::{
    collections::{BTreeMap, BTreeSet},
    fs::{self, File, OpenOptions},
    io::{Read, Write},
    path::{Component, Path, PathBuf},
    sync::atomic::{AtomicU64, Ordering},
    time::{SystemTime, UNIX_EPOCH},
};

type Result<T> = std::result::Result<T, String>;
const PRODUCER: &str = "khor-gui-bindings";
const INVENTORY: &str = ".khor-bindings.json";
pub(super) const HEADER: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n";
const MAX_FILES: usize = 4096;
const MAX_FILE_BYTES: u64 = 16 * 1024 * 1024;
const MAX_RECORD_BYTES: u64 = 2 * 1024 * 1024;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Inventory {
    version: u32,
    producer: String,
    files: BTreeMap<String, String>,
}
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Tree {
    inventory: Inventory,
    managed: bool,
}
#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Journal {
    version: u32,
    producer: String,
    target: String,
    stage: String,
    backup: String,
    old: Option<Tree>,
    new: Inventory,
}
struct Layout {
    target: PathBuf,
    parent: PathBuf,
    leaf: String,
    journal: PathBuf,
    lock: PathBuf,
}

pub(super) fn type_name(path: &Path) -> Result<String> {
    let name = path.to_str().ok_or("non-UTF8 type output path")?;
    let mut components = path.components();
    if !matches!(components.next(), Some(Component::Normal(_)))
        || components.next().is_some()
        || !name.ends_with(".ts")
        || name.len() <= 3
        || name.chars().any(|c| matches!(c, '/' | '\\' | ':'))
        || name.chars().any(char::is_control)
    {
        return Err(format!(
            "type output must be a flat relative .ts file: {name:?}"
        ));
    }
    Ok(name.into())
}
fn exists(path: &Path) -> Result<bool> {
    match fs::symlink_metadata(path) {
        Ok(_) => Ok(true),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(format!("inspect {}: {error}", path.display())),
    }
}
fn regular(path: &Path) -> Result<()> {
    if !fs::symlink_metadata(path)
        .map_err(|e| format!("inspect {}: {e}", path.display()))?
        .file_type()
        .is_file()
    {
        return Err(format!("not a regular file: {}", path.display()));
    }
    Ok(())
}
fn read_bytes(path: &Path, limit: u64) -> Result<Vec<u8>> {
    regular(path)?;
    let mut bytes = Vec::new();
    File::open(path)
        .and_then(|f| f.take(limit + 1).read_to_end(&mut bytes))
        .map_err(|e| format!("read {}: {e}", path.display()))?;
    if bytes.len() as u64 > limit {
        return Err(format!("file exceeds generator budget: {}", path.display()));
    }
    Ok(bytes)
}
fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T> {
    serde_json::from_slice(&read_bytes(path, MAX_RECORD_BYTES)?)
        .map_err(|e| format!("invalid record {}: {e}", path.display()))
}
fn sync_dir(path: &Path) -> Result<()> {
    #[cfg(unix)]
    File::open(path)
        .and_then(|f| f.sync_all())
        .map_err(|e| format!("sync {}: {e}", path.display()))?;
    #[cfg(not(unix))]
    let _ = path;
    Ok(())
}
fn write_json(path: &Path, value: &impl Serialize) -> Result<()> {
    let bytes = serde_json::to_vec_pretty(value).map_err(|e| e.to_string())?;
    if bytes.len() as u64 > MAX_RECORD_BYTES {
        return Err("generator record exceeds budget".into());
    }
    let mut options = OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = options
        .open(path)
        .map_err(|e| format!("create {}: {e}", path.display()))?;
    file.write_all(&bytes)
        .and_then(|_| file.sync_all())
        .map_err(|e| format!("write {}: {e}", path.display()))
}
fn entries(path: &Path) -> Result<BTreeMap<String, PathBuf>> {
    if !fs::symlink_metadata(path)
        .map_err(|e| format!("inspect {}: {e}", path.display()))?
        .file_type()
        .is_dir()
    {
        return Err(format!("not a real directory: {}", path.display()));
    }
    let mut files = BTreeMap::new();
    for (index, entry) in fs::read_dir(path).map_err(|e| e.to_string())?.enumerate() {
        if index > MAX_FILES {
            return Err("too many generator directory entries".into());
        }
        let entry = entry.map_err(|e| e.to_string())?;
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| "non-UTF8 directory entry")?;
        regular(&entry.path())?;
        if name != INVENTORY {
            type_name(Path::new(&name))?;
        }
        files.insert(name, entry.path());
    }
    Ok(files)
}
fn valid_inventory(value: &Inventory) -> Result<()> {
    if value.version != 1 || value.producer != PRODUCER || value.files.len() > MAX_FILES {
        return Err("unknown bindings inventory".into());
    }
    for (name, hash) in &value.files {
        type_name(Path::new(name))?;
        if hash.len() != 64 || !hash.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err("invalid bindings inventory digest".into());
        }
    }
    Ok(())
}
fn inspect(path: &Path, adopt: bool) -> Result<Tree> {
    let mut listing = entries(path)?;
    let manifest = listing.remove(INVENTORY);
    let mut files = BTreeMap::new();
    for (name, path) in listing {
        let bytes = read_bytes(&path, MAX_FILE_BYTES)?;
        if !bytes.starts_with(HEADER.as_bytes()) {
            return Err(format!("not a generated binding: {}", path.display()));
        }
        files.insert(name, blake3::hash(&bytes).to_hex().to_string());
    }
    let inventory = Inventory {
        version: 1,
        producer: PRODUCER.into(),
        files,
    };
    valid_inventory(&inventory)?;
    if let Some(manifest) = manifest {
        let previous: Inventory = read_json(&manifest)?;
        valid_inventory(&previous)?;
        if previous != inventory {
            return Err(format!(
                "bindings inventory differs from files: {}",
                path.display()
            ));
        }
        Ok(Tree {
            inventory,
            managed: true,
        })
    } else if adopt || inventory.files.is_empty() {
        Ok(Tree {
            inventory,
            managed: false,
        })
    } else {
        Err(format!(
            "refuse unmanaged nonempty output directory: {}",
            path.display()
        ))
    }
}
// Validate the complete remaining whitelist before unlinking even one entry.
// A prior interrupted cleanup may have removed a subset of these exact files.
fn known_listing(path: &Path, tree: &Tree) -> Result<BTreeMap<String, PathBuf>> {
    if !exists(path)? {
        return Ok(BTreeMap::new());
    }
    let listing = entries(path)?;
    for (name, file) in &listing {
        if name == INVENTORY {
            if !tree.managed || read_json::<Inventory>(file)? != tree.inventory {
                return Err(format!("unexpected inventory in {}", path.display()));
            }
        } else {
            let hash = tree
                .inventory
                .files
                .get(name)
                .ok_or_else(|| format!("unknown retained file: {}", file.display()))?;
            if blake3::hash(&read_bytes(file, MAX_FILE_BYTES)?)
                .to_hex()
                .as_str()
                != hash.as_str()
            {
                return Err(format!("retained file changed: {}", file.display()));
            }
        }
    }
    Ok(listing)
}
fn remove_known(path: &Path, tree: &Tree) -> Result<()> {
    if !exists(path)? {
        return Ok(());
    }
    let listing = known_listing(path, tree)?;
    for file in listing.values() {
        fs::remove_file(file).map_err(|e| format!("remove {}: {e}", file.display()))?;
    }
    fs::remove_dir(path).map_err(|e| format!("remove {}: {e}", path.display()))?;
    sync_dir(path.parent().ok_or("missing output parent")?)
}
fn remove_partial_stage(path: &Path, planned: &BTreeSet<String>) -> Result<()> {
    let listing = entries(path)?;
    for name in listing.keys() {
        if name != INVENTORY && !planned.contains(name) {
            return Err(format!("unknown stage entry retained: {name}"));
        }
    }
    // This fresh private stage is owned by this invocation. Partial writes to
    // planned paths are allowed; symlinks/unknown paths were rejected above.
    for file in listing.values() {
        fs::remove_file(file).map_err(|e| e.to_string())?;
    }
    fs::remove_dir(path).map_err(|e| e.to_string())
}

impl Layout {
    fn new(output: &Path) -> Result<Self> {
        let absolute = if output.is_absolute() {
            output.to_path_buf()
        } else {
            std::env::current_dir()
                .map_err(|e| e.to_string())?
                .join(output)
        };
        // The selected temporary root can itself be an OS alias (macOS /var).
        // Resolve that anchor once, then reject links beneath it like any
        // other output ancestry. Never canonicalize the output directory.
        let temporary = std::env::temp_dir();
        let absolute = if let Ok(relative) = absolute.strip_prefix(&temporary) {
            temporary
                .canonicalize()
                .map_err(|e| e.to_string())?
                .join(relative)
        } else {
            absolute
        };
        let mut target = PathBuf::new();
        for component in absolute.components() {
            match component {
                Component::ParentDir => {
                    if !target.pop() {
                        return Err("output escapes root".into());
                    }
                }
                Component::CurDir => {}
                other => target.push(other.as_os_str()),
            }
        }
        let leaf = target
            .file_name()
            .and_then(|s| s.to_str())
            .ok_or("output needs a directory name")?
            .to_owned();
        let parent = target
            .parent()
            .ok_or("output needs a parent")?
            .to_path_buf();
        let mut part = PathBuf::new();
        for component in parent.components() {
            part.push(component.as_os_str());
            if !exists(&part)? {
                fs::create_dir(&part).map_err(|e| e.to_string())?;
            }
            if !fs::symlink_metadata(&part)
                .map_err(|e| e.to_string())?
                .file_type()
                .is_dir()
            {
                return Err(format!(
                    "output parent is not a real directory: {}",
                    part.display()
                ));
            }
        }
        Ok(Self {
            journal: parent.join(format!(".{leaf}.khor-bindings-transaction.json")),
            lock: parent.join(format!(".{leaf}.khor-bindings.lock")),
            target,
            parent,
            leaf,
        })
    }
    fn lock(&self) -> Result<File> {
        if exists(&self.lock)? {
            regular(&self.lock)?;
        }
        let mut options = OpenOptions::new();
        options.create(true).truncate(false).read(true).write(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let file = options.open(&self.lock).map_err(|e| e.to_string())?;
        file.try_lock()
            .map_err(|_| "bindings output is busy".to_owned())?;
        Ok(file)
    }
    fn journal(&self) -> Result<Journal> {
        let journal: Journal = read_json(&self.journal)?;
        let prefix = format!(".{}.stage-", self.leaf);
        let nonce = journal
            .stage
            .strip_prefix(&prefix)
            .ok_or("invalid stage identity")?;
        if nonce.is_empty()
            || !nonce.bytes().all(|b| b.is_ascii_digit() || b == b'-')
            || journal.version != 1
            || journal.producer != PRODUCER
            || journal.target != self.leaf
            || journal.backup != format!(".{}.backup-{nonce}", self.leaf)
        {
            return Err("invalid bindings publication record".into());
        }
        valid_inventory(&journal.new)?;
        if let Some(old) = &journal.old {
            valid_inventory(&old.inventory)?;
        }
        Ok(journal)
    }
    fn clear_journal(&self) -> Result<()> {
        fs::remove_file(&self.journal).map_err(|e| format!("remove journal: {e}"))?;
        sync_dir(&self.parent)
    }
    fn recover(&self) -> Result<()> {
        if !exists(&self.journal)? {
            return Ok(());
        }
        let journal = self.journal()?;
        let stage = self.parent.join(&journal.stage);
        let backup = self.parent.join(&journal.backup);
        let new = Tree {
            inventory: journal.new.clone(),
            managed: true,
        };
        if exists(&self.target)? {
            let current = inspect(
                &self.target,
                journal.old.as_ref().is_some_and(|old| !old.managed),
            )?;
            if current == new {
                // Check both cleanup directories before the first unlink.
                known_listing(&stage, &new)?;
                match &journal.old {
                    Some(old) => {
                        known_listing(&backup, old)?;
                    }
                    None if exists(&backup)? => return Err("unexpected backup retained".into()),
                    None => {}
                }
                remove_known(&stage, &new)?;
                if let Some(old) = &journal.old {
                    remove_known(&backup, old)?;
                }
            } else if journal.old.as_ref() == Some(&current) && !exists(&backup)? {
                remove_known(&stage, &new)?;
            } else {
                return Err("publication differs from journal; all outputs retained".into());
            }
        } else if let Some(old) = &journal.old {
            if inspect(&backup, !old.managed)? != *old {
                return Err("previous bindings differ from backup; retained".into());
            }
            fs::rename(&backup, &self.target)
                .map_err(|e| format!("restore previous bindings: {e}"))?;
            sync_dir(&self.parent)?;
            remove_known(&stage, &new)?;
        } else {
            if exists(&backup)? || inspect(&stage, false)? != new {
                return Err("incomplete fresh publication retained".into());
            }
            fs::rename(&stage, &self.target).map_err(|e| e.to_string())?;
            sync_dir(&self.parent)?;
        }
        self.clear_journal()
    }
}

pub(super) fn generate(
    output: &Path,
    default_output: bool,
    planned: &BTreeSet<String>,
    export: impl FnOnce(&Path) -> Result<()>,
) -> Result<()> {
    generate_with(output, default_output, planned, export, || Ok(()))
}
fn generate_with(
    output: &Path,
    default_output: bool,
    planned: &BTreeSet<String>,
    export: impl FnOnce(&Path) -> Result<()>,
    after_backup: impl FnOnce() -> Result<()>,
) -> Result<()> {
    if planned.len() > MAX_FILES {
        return Err("too many planned bindings".into());
    }
    for name in planned {
        type_name(Path::new(name))?;
    }
    let layout = Layout::new(output)?;
    let _lock = layout.lock()?;
    layout.recover()?;
    let old = if exists(&layout.target)? {
        Some(inspect(&layout.target, default_output)?)
    } else {
        None
    };
    static SERIAL: AtomicU64 = AtomicU64::new(0);
    let nonce = format!(
        "{}-{}-{}",
        std::process::id(),
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_err(|e| e.to_string())?
            .as_nanos(),
        SERIAL.fetch_add(1, Ordering::Relaxed)
    );
    let stage_name = format!(".{}.stage-{nonce}", layout.leaf);
    let backup_name = format!(".{}.backup-{nonce}", layout.leaf);
    let stage = layout.parent.join(&stage_name);
    let backup = layout.parent.join(&backup_name);
    let mut builder = fs::DirBuilder::new();
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        builder.mode(0o700);
    }
    builder.create(&stage).map_err(|e| e.to_string())?;
    let prepared = (|| {
        export(&stage)?;
        let new = inspect(&stage, true)?;
        if new.managed || new.inventory.files.keys().cloned().collect::<BTreeSet<_>>() != *planned {
            return Err("exported bindings differ from planned type paths".into());
        }
        write_json(&stage.join(INVENTORY), &new.inventory)?;
        sync_dir(&stage)?;
        Ok(new.inventory)
    })();
    let new = match prepared {
        Ok(new) => new,
        Err(error) => {
            return match remove_partial_stage(&stage, planned) {
                Ok(()) => Err(error),
                Err(cleanup) => Err(format!(
                    "{error}; stage retained at {}: {cleanup}",
                    stage.display()
                )),
            };
        }
    };
    if exists(&backup)? {
        return Err(format!("unexpected backup retained: {}", backup.display()));
    }
    let journal = Journal {
        version: 1,
        producer: PRODUCER.into(),
        target: layout.leaf.clone(),
        stage: stage_name,
        backup: backup_name,
        old,
        new,
    };
    // The record is complete and synced before either live directory moves.
    write_json(&layout.journal, &journal)?;
    sync_dir(&layout.parent)?;
    let published = (|| {
        if journal.old.is_some() {
            fs::rename(&layout.target, &backup)
                .map_err(|e| format!("keep previous bindings: {e}"))?;
            sync_dir(&layout.parent)?;
        }
        after_backup()?;
        if exists(&layout.target)? {
            return Err("output appeared during publication".into());
        }
        fs::rename(&stage, &layout.target).map_err(|e| format!("publish bindings: {e}"))?;
        sync_dir(&layout.parent)
    })();
    if let Err(error) = published {
        if !exists(&layout.target)? && journal.old.is_some() {
            // Roll back only the exact validated old tree; never remove a
            // foreign destination to make rollback succeed.
            if let Err(recovery) = layout.recover() {
                return Err(format!(
                    "{error}; previous output retained at {}: {recovery}",
                    backup.display()
                ));
            }
            return Err(format!("{error}; previous bindings restored"));
        }
        return Err(format!(
            "{error}; publication record retained at {}",
            layout.journal.display()
        ));
    }
    // Recovery also completes interrupted cleanup. It checks the entire
    // remaining whitelist before deleting any exact backup/stage entry.
    layout
        .recover()
        .map_err(|e| format!("bindings published; cleanup incomplete: {e}"))
}

