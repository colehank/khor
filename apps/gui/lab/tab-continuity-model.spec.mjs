import {build} from 'esbuild';
import assert from 'node:assert/strict';
const {outputFiles}=await build({entryPoints:[new URL('./tab-continuity-model.ts',import.meta.url).pathname],bundle:true,write:false,format:'esm',platform:'node'});
const {rootTab,addChild,pointChild,changeChild,closeChild,reorder}=await import('data:text/javascript;base64,'+Buffer.from(outputFiles[0].text).toString('base64'));
let root=addChild(rootTab());
const first=root.active;
root=changeChild(root,first,{place:{...root.tabs[0].place,scope:{device:'mac',root:'/Users/zgh/Projects/one'},query:'README'}});
root=addChild(root);
const second=root.active;
assert.notEqual(first,second);
assert.equal(root.tabs.length,2);
assert.equal(root.tabs[1].place.query,'');
assert.equal(root.tabs[1].place.scope.root,'/Users/zgh/Projects/one');
root=changeChild(root,second,{place:{...root.tabs[1].place,source:'browser',address:'https://example.org'}});
assert.equal(root.tabs[0].place.source,'workspace');
root=pointChild(root,first,'/Users/zgh/Projects/one/README.md','file');
assert.equal(root.tabs[0].id,first);
assert.equal(root.tabs.length,2);
assert.equal(root.tabs[0].title,'README.md');
root=pointChild(root,second,'https://example.org','page');
assert.equal(root.tabs[1].id,second);
assert.equal(root.active,second);
const ordered=reorder(root.tabs,[second,first]);
assert.deepEqual(ordered.map(t=>t.id),[second,first]);
assert.equal(ordered[1],root.tabs[0]);
root=closeChild(root,second);
assert.equal(root.active,first);
assert.equal(root.expanded,true);
root=closeChild(root,first);
assert.equal(root.active,null);
assert.equal(root.expanded,false);
assert.equal(root.tabs.length,0);
console.log('PASS: independent blank tabs, context isolation, stable identity, reorder, neighbour selection, close-last collapse');
