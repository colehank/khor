// The site reads its values from the design system, never from a copy:
// `docs/design-system/tokens.json` is where a value is decided, and
// this prints it as CSS custom properties before every dev/build. A
// second hand-kept table would drift the way tokens.css once did —
// the app needs `check-boot` to hold its copy; the site has no copy.
//
// Dark follows the system (`prefers-color-scheme`). The app has a
// toggle because it is lived in; a page read once does not earn one.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const src = new URL("../../../docs/design-system/tokens.json", import.meta.url);
const out = new URL("../src/styles/tokens.gen.css", import.meta.url);
const t = JSON.parse(readFileSync(src, "utf8"));

const light = [];
const dark = [];
const put = (name, value) => {
  if (typeof value === "object") {
    light.push(`--${name}: ${value.light};`);
    dark.push(`--${name}: ${value.dark};`);
  } else {
    light.push(`--${name}: ${value};`);
  }
};

for (const k of t.color.tokens) put(k.name, k.value);
// `knob` names a colour and a shadow, so shadows carry their kind.
for (const k of t.shadow.tokens) put(`shadow-${k.name}`, k.value);
for (const group of ["spacing", "radius", "size", "opacity", "duration", "easing"])
  for (const k of t[group].tokens) put(k.name, k.value);
for (const [name, stack] of Object.entries(t.type.families)) put(name, stack);
for (const g of t.type.groups)
  for (const s of g.styles) {
    put(`text-${s.name}`, s.fontSize);
    put(`text-${s.name}--line-height`, s.lineHeight);
    put(`text-${s.name}--weight`, s.fontWeight);
  }

const block = (lines, pad) => lines.map((l) => pad + l).join("\n");
const css = `/* Generated by scripts/tokens.mjs from docs/design-system/tokens.json — edit that, not this. */
:root {
  color-scheme: light dark;
${block(light, "  ")}
}
@media (prefers-color-scheme: dark) {
  :root {
${block(dark, "    ")}
  }
}
`;
mkdirSync(new URL("./", out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens: ${light.length} values, ${dark.length} with a dark half`);
